const GameBuilder = (() => {
  const GRID_SIZE = 16;
  let matrix = [];
  let currentTileType = 1;
  let isDrawing = false;
  let onMatrixChangeCallback = null;

  const TILES = {
    0: { id: 0, name: 'Trống (Empty)', color: '#0d1117', icon: '⬛' },
    1: { id: 1, name: 'Tường Đá (Wall)', color: '#30363d', icon: '🧱' },
    2: { id: 2, name: 'Đường Đi (Path)', color: '#21262d', icon: '🟩' },
    3: { id: 3, name: 'Đồng Xu (Coin)', color: '#d29922', icon: '🪙' },
    4: { id: 4, name: 'Người Chơi (Player)', color: '#58a6ff', icon: '🧙' },
    5: { id: 5, name: 'Quái Vật (Enemy)', color: '#f85149', icon: '👾' },
    6: { id: 6, name: 'Cổng Về Đích (Exit)', color: '#3fb950', icon: '🏆' },
    7: { id: 7, name: 'Bẫy Gai (Spike/Lava)', color: '#ff7b72', icon: '🔥' }
  };

  function init(initialMatrix = null, onMatrixChange = null) {
    onMatrixChangeCallback = onMatrixChange;
    if (initialMatrix && Array.isArray(initialMatrix)) {
      matrix = initialMatrix;
    } else {
      matrix = [];
      for (let r = 0; r < GRID_SIZE; r++) {
        const row = [];
        for (let c = 0; c < GRID_SIZE; c++) {
          if (r === 0 || r === GRID_SIZE - 1 || c === 0 || c === GRID_SIZE - 1) {
            row.push(1);
          } else {
            row.push(0);
          }
        }
        matrix.push(row);
      }

      matrix[1][1] = 4;
      matrix[14][14] = 6;
      matrix[3][3] = 3;
      matrix[8][8] = 3;
      matrix[5][10] = 5;
    }
    notifyMatrixUpdate();
  }

  function notifyMatrixUpdate() {
    if (typeof onMatrixChangeCallback === 'function') {
      onMatrixChangeCallback(exportMatrixCode());
    }
  }

  function exportMatrixCode() {
    return '// Ma Trận Bản Đồ Game 2D (Tilemap Matrix)\n' +
      'const MAP_GRID = ' + JSON.stringify(matrix, null, 2) + ';\n\n' +
      '// Chú giải Tile: 0: Trống, 1: Tường, 2: Đất, 3: Coin, 4: Player, 5: Enemy, 6: Đích\n';
  }

  function setTileType(typeId) {
    currentTileType = typeId;
    document.querySelectorAll('.tile-palette-btn').forEach(btn => {
      btn.classList.toggle('active', parseInt(btn.dataset.type) === typeId);
    });
  }

  function setCell(r, c) {
    if (r < 0 || r >= GRID_SIZE || c < 0 || c >= GRID_SIZE) return;
    matrix[r][c] = currentTileType;
    notifyMatrixUpdate();
    renderGridCells();
  }

  function clearGrid() {
    for (let r = 0; r < GRID_SIZE; r++) {
      for (let c = 0; c < GRID_SIZE; c++) {
        matrix[r][c] = (r === 0 || r === GRID_SIZE - 1 || c === 0 || c === GRID_SIZE - 1) ? 1 : 0;
      }
    }
    matrix[1][1] = 4;
    matrix[GRID_SIZE - 2][GRID_SIZE - 2] = 6;
    notifyMatrixUpdate();
    renderGridCells();
  }

  function generateRandomMaze() {
    for (let r = 1; r < GRID_SIZE - 1; r++) {
      for (let c = 1; c < GRID_SIZE - 1; c++) {
        if (Math.random() < 0.25) {
          matrix[r][c] = 1;
        } else if (Math.random() < 0.08) {
          matrix[r][c] = 3;
        } else if (Math.random() < 0.03) {
          matrix[r][c] = 5;
        } else {
          matrix[r][c] = 0;
        }
      }
    }
    matrix[1][1] = 4;
    matrix[GRID_SIZE - 2][GRID_SIZE - 2] = 6;
    notifyMatrixUpdate();
    renderGridCells();
  }

  function renderStudio(containerId) {
    const container = document.getElementById(containerId);
    if (!container) return;

    container.innerHTML = `
      <div class="game-studio-layout">
        <!-- 1. LEFT: Tile Palette & Tools -->
        <div class="game-palette">
          <div class="palette-header">
            <span class="palette-title">🎨 Bảng Tile Game</span>
          </div>
          <div class="tile-palette-grid">
            ${Object.values(TILES).map(t => `
              <button class="tile-palette-btn ${currentTileType === t.id ? 'active' : ''}" data-type="${t.id}" onclick="GameBuilder.setTileType(${t.id})">
                <span class="tile-icon">${t.icon}</span>
                <span class="tile-label">${t.name}</span>
              </button>
            `).join('')}
          </div>
          <div class="game-tools-section">
            <button class="tool-btn" onclick="GameBuilder.generateRandomMaze()">🎲 Tạo Mê Cung Tự Động</button>
            <button class="tool-btn danger" onclick="GameBuilder.clearGrid()">🗑️ Xóa Lưới</button>
          </div>
        </div>

        <!-- 2. CENTER: Tilemap Matrix Canvas Grid -->
        <div class="game-canvas-wrapper">
          <div class="canvas-toolbar">
            <span class="canvas-tag">🗺️ Vẽ Bản Đồ Ma Trận (Nhấp & Kéo chuột để vẽ)</span>
            <div class="canvas-actions">
              <button class="game-run-btn" onclick="GameBuilder.runPlayableGame('game-live-canvas')">▶️ Chạy Thử Game 2D</button>
            </div>
          </div>
          <div class="tilemap-grid-container" id="tilemap-grid">
            <!-- Grid generated by renderGridCells() -->
          </div>
        </div>

        <!-- 3. RIGHT: Live Playable Game Engine 2D -->
        <div class="game-runner-panel">
          <div class="runner-header">
            <span>🎮 Màn Hình Chạy Game</span>
          </div>
          <div class="game-screen-wrapper">
            <canvas id="game-live-canvas" width="320" height="320"></canvas>
            <div class="game-controls-help">
              <span>⌨️ Phím điều khiển: Phím Mũi Tên (⬆️ ⬇️ ⬅️ ➡️) hoặc WASD để di chuyển.</span>
            </div>
          </div>
          <div class="game-stats-box" id="game-stats">
            <div>🪙 Điểm Coin: <strong id="game-score">0</strong></div>
            <div>❤️ Trạng thái: <strong id="game-status" style="color:#3fb950">Sẵn sàng</strong></div>
          </div>
        </div>
      </div>
    `;

    renderGridCells();
    setTimeout(() => runPlayableGame('game-live-canvas'), 100);
  }

  function renderGridCells() {
    const gridEl = document.getElementById('tilemap-grid');
    if (!gridEl) return;

    let html = '';
    for (let r = 0; r < GRID_SIZE; r++) {
      html += '<div class="grid-row">';
      for (let c = 0; c < GRID_SIZE; c++) {
        const val = matrix[r]?.[c] || 0;
        const tile = TILES[val] || TILES[0];
        html += `<div class="grid-cell tile-${val}" data-r="${r}" data-c="${c}" onmousedown="GameBuilder.setCell(${r}, ${c})" onmouseenter="if(event.buttons===1)GameBuilder.setCell(${r}, ${c})">${tile.icon}</div>`;
      }
      html += '</div>';
    }
    gridEl.innerHTML = html;
  }

  let gameInterval = null;
  let playerPos = { r: 1, c: 1 };
  let gameScore = 0;
  let gameRunning = false;

  function runPlayableGame(canvasId) {
    const canvas = document.getElementById(canvasId);
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    const cellSize = canvas.width / GRID_SIZE;

    gameScore = 0;
    gameRunning = true;
    document.getElementById('game-score').textContent = '0';
    document.getElementById('game-status').textContent = 'Đang chơi...';
    document.getElementById('game-status').style.color = '#58a6ff';

    const playMatrix = JSON.parse(JSON.stringify(matrix));

    for (let r = 0; r < GRID_SIZE; r++) {
      for (let c = 0; c < GRID_SIZE; c++) {
        if (playMatrix[r][c] === 4) {
          playerPos = { r, c };
          playMatrix[r][c] = 0;
        }
      }
    }

    function draw() {
      ctx.clearRect(0, 0, canvas.width, canvas.height);

      for (let r = 0; r < GRID_SIZE; r++) {
        for (let c = 0; c < GRID_SIZE; c++) {
          const val = playMatrix[r][c];
          const x = c * cellSize;
          const y = r * cellSize;

          if (val === 1) {
            ctx.fillStyle = '#30363d';
            ctx.fillRect(x, y, cellSize, cellSize);
            ctx.strokeStyle = '#21262d';
            ctx.strokeRect(x, y, cellSize, cellSize);
          } else if (val === 3) {

            ctx.fillStyle = '#d29922';
            ctx.beginPath();
            ctx.arc(x + cellSize/2, y + cellSize/2, cellSize/3, 0, Math.PI * 2);
            ctx.fill();
          } else if (val === 5) {

            ctx.fillStyle = '#f85149';
            ctx.fillRect(x + 2, y + 2, cellSize - 4, cellSize - 4);
          } else if (val === 6) {

            ctx.fillStyle = '#3fb950';
            ctx.fillRect(x, y, cellSize, cellSize);
          } else {

            ctx.fillStyle = '#0d1117';
            ctx.fillRect(x, y, cellSize, cellSize);
          }
        }
      }

      const px = playerPos.c * cellSize;
      const py = playerPos.r * cellSize;
      ctx.fillStyle = '#58a6ff';
      ctx.beginPath();
      ctx.arc(px + cellSize/2, py + cellSize/2, cellSize/2.2, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = '#ffffff';
      ctx.fillText('🧙', px + 2, py + cellSize - 4);
    }

    function handleKeyDown(e) {
      if (!gameRunning) return;
      let nr = playerPos.r;
      let nc = playerPos.c;

      if (e.key === 'ArrowUp' || e.key === 'w' || e.key === 'W') nr--;
      else if (e.key === 'ArrowDown' || e.key === 's' || e.key === 'S') nr++;
      else if (e.key === 'ArrowLeft' || e.key === 'a' || e.key === 'A') nc--;
      else if (e.key === 'ArrowRight' || e.key === 'd' || e.key === 'D') nc++;
      else return;

      e.preventDefault();

      if (nr < 0 || nr >= GRID_SIZE || nc < 0 || nc >= GRID_SIZE || playMatrix[nr][nc] === 1) {
        return;
      }

      playerPos = { r: nr, c: nc };

      if (playMatrix[nr][nc] === 3) {
        playMatrix[nr][nc] = 0;
        gameScore += 10;
        const scoreEl = document.getElementById('game-score');
        if (scoreEl) scoreEl.textContent = gameScore;
      }

      if (playMatrix[nr][nc] === 5) {
        gameRunning = false;
        const statusEl = document.getElementById('game-status');
        if (statusEl) {
          statusEl.textContent = '❌ Thất bại! Đã đụng quái vật!';
          statusEl.style.color = '#f85149';
        }
      }

      if (playMatrix[nr][nc] === 6) {
        gameRunning = false;
        const statusEl = document.getElementById('game-status');
        if (statusEl) {
          statusEl.textContent = '🎉 CHIẾN THẮNG! Điểm: ' + gameScore;
          statusEl.style.color = '#3fb950';
        }
      }

      draw();
    }

    window.removeEventListener('keydown', window._gameKeyHandler);
    window._gameKeyHandler = handleKeyDown;
    window.addEventListener('keydown', handleKeyDown);

    draw();
  }

  return {
    init,
    renderStudio,
    setTileType,
    setCell,
    clearGrid,
    generateRandomMaze,
    exportMatrixCode,
    runPlayableGame
  };
})();

if (typeof window !== 'undefined') {
  window.GameBuilder = GameBuilder;
}
